def _norm_nome_lotacao(s: str) -> str:
    nfkd = unicodedata.normalize("NFKD", str(s or ""))
    sem = "".join(c for c in nfkd if not unicodedata.combining(c))
    toks = [t for t in re.sub(r"[^A-Za-z0-9\s]", " ", sem).upper().split() if t not in {"DE", "DA", "DO", "DOS", "DAS"}]
    return " ".join(toks)


_LOTACAO_NORM: list[tuple[str, str]] = sorted(
    [(_norm_nome_lotacao(k), v) for k, v in LOTACAO_COLABORADORES.items()],
    key=lambda x: len(x[0]),
    reverse=True,
)
_LOTACAO_EXATA: dict[str, str] = dict(_LOTACAO_NORM)


def resolver_filial_colaborador(nome: str, fallback: str = "A Classificar") -> str:
    chave = _norm_nome_lotacao(nome)
    if not chave:
        return fallback
    if chave in _LOTACAO_EXATA:
        return _LOTACAO_EXATA[chave]
    for k_norm, fil in _LOTACAO_NORM:
        if len(k_norm) >= 8 and (k_norm in chave or chave in k_norm):
            return fil
    return fallback
